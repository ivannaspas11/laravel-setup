<?php


// 1. Створення базового PHP-скрипта


// Виводимо на екран текст "Hello, World!" за допомогою echo.
echo "Hello, World!";

// Тег <br> переносить наступний текст на новий рядок у браузері.
echo "<br><br>";



// 2. Змінні та типи даних


// Оголошуємо змінну типу string (рядок).
$name = "Софія";

// Оголошуємо змінну типу integer (ціле число).
$age = 20;

// Оголошуємо змінну типу float (число з плаваючою комою).
$average = 89.5;

// Оголошуємо змінну типу boolean (булеве значення).
$isStudent = true;

// Виводимо значення змінної $name на екран.
echo "Ім'я: " . $name . "<br>";

// Виводимо значення змінної $age на екран.
echo "Вік: " . $age . "<br>";

// Виводимо значення змінної $average на екран.
echo "Середній бал: " . $average . "<br>";

// Виводимо значення булевої змінної.
// Для true виводимо текст "Так", оскільки echo для boolean true
// безпосередньо виводить число 1.
echo "Студент: " . ($isStudent ? "Так" : "Ні") . "<br><br>";

// Функція var_dump() показує тип та значення змінної.
echo "Тип змінної \$name: ";
var_dump($name);
echo "<br>";

echo "Тип змінної \$age: ";
var_dump($age);
echo "<br>";

echo "Тип змінної \$average: ";
var_dump($average);
echo "<br>";

echo "Тип змінної \$isStudent: ";
var_dump($isStudent);
echo "<br><br>";



// 3. Конкатенація рядків


// Створюємо першу змінну з рядковим значенням.
$firstWord = "Hello";

// Створюємо другу змінну з рядковим значенням.
$secondWord = "World";

// Об'єднуємо два рядки за допомогою оператора ".".
$fullText = $firstWord . ", " . $secondWord . "!";

// Виводимо отриманий об'єднаний рядок.
echo "Результат конкатенації: " . $fullText . "<br><br>";



// 4. Умовні конструкції


// Створюємо змінну з числовим значенням.
$number = 15;

// Перевіряємо, чи ділиться число на 2 без остачі.
// Оператор % повертає залишок від ділення.
if ($number % 2 == 0) {

    // Якщо залишок дорівнює 0, число є парним.
    echo "Число " . $number . " є парним.";

} else {

    // Якщо залишок не дорівнює 0, число є непарним.
    echo "Число " . $number . " є непарним.";
}

echo "<br><br>";



// 5. Цикли

// Цикл for виводить числа від 1 до 10.
echo "Числа від 1 до 10:<br>";

for ($i = 1; $i <= 10; $i++) {

    // Виводимо поточне значення лічильника.
    echo $i . " ";
}

echo "<br><br>";

// Створюємо початкове значення для циклу while.
$i = 10;

// Виводимо числа від 10 до 1.
echo "Числа від 10 до 1:<br>";

while ($i >= 1) {

    // Виводимо поточне значення змінної.
    echo $i . " ";

    // Зменшуємо значення змінної на 1.
    $i--;
}

echo "<br><br>";



// 6. Масиви


// Створюємо асоціативний масив з інформацією про студента.
$student = [
    "ім'я" => "Софія",
    "прізвище" => "Ходак",
    "вік" => 20,
    "спеціальність" => "Комп'ютерні науки"
];

// Виводимо значення кожного елемента масиву.
echo "Ім'я: " . $student["ім'я"] . "<br>";
echo "Прізвище: " . $student["прізвище"] . "<br>";
echo "Вік: " . $student["вік"] . "<br>";
echo "Спеціальність: " . $student["спеціальність"] . "<br><br>";

// Додаємо до масиву новий елемент — середній бал студента.
$student["середній бал"] = 89.5;

// Виводимо оновлений масив.
// print_r() зручно використовувати для перегляду структури масиву.
echo "Оновлений масив студента:<br>";
echo "<pre>";
print_r($student);
echo "</pre>";

?>