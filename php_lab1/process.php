<?php


// Обробка даних форми


// Перевіряємо, чи форма була відправлена методом POST.
if ($_SERVER["REQUEST_METHOD"] === "POST") {

    // Отримуємо ім'я з форми.
    // Оператор ?? повертає порожній рядок, якщо поле відсутнє.
    $firstName = $_POST["first_name"] ?? "";

    // Отримуємо прізвище з форми.
    $lastName = $_POST["last_name"] ?? "";


   
    // Перевірка типу даних
    

    // Перевіряємо, чи є ім'я та прізвище рядками.
    if (!is_string($firstName) || !is_string($lastName)) {

        // Якщо дані не є рядками, виводимо повідомлення про помилку.
        echo "Помилка: ім'я та прізвище повинні бути текстовими значеннями.";

        // Завершуємо виконання скрипта.
        exit;
    }


    
    // Перевірка на порожні значення
    
    // trim() видаляє зайві пробіли на початку та в кінці рядка.
    $firstName = trim($firstName);
    $lastName = trim($lastName);

    // Перевіряємо, чи не залишилися поля порожніми.
    if ($firstName === "" || $lastName === "") {

        // Виводимо повідомлення про помилку.
        echo "Помилка: будь ласка, заповніть поля «Ім'я» та «Прізвище».";

        // Завершуємо виконання скрипта.
        exit;
    }


    
    // Виведення привітання
    

    // htmlspecialchars() захищає виведений текст від HTML-коду.
    $safeFirstName = htmlspecialchars($firstName, ENT_QUOTES, "UTF-8");
    $safeLastName = htmlspecialchars($lastName, ENT_QUOTES, "UTF-8");

    // Виводимо привітання користувачу.
    echo "<h1>Вітаємо!</h1>";

    echo "<p>Привіт, "
        . $safeFirstName
        . " "
        . $safeLastName
        . "!</p>";

} else {

    // Якщо process.php відкрили без відправлення форми,
    // виводимо відповідне повідомлення.
    echo "Помилка: дані форми не були отримані.";
}

?>